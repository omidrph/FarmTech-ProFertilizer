# هیدروپونیک (مورد استفاده در مراجعی مثل Sonneveld & Voogt، "Plant
# Nutrition of Greenhouse Crops") این است:
#
#     EC (dS/m) ≈ (مجموع meq/L آنیون‌ها یا کاتیون‌ها، که باید تقریباً
#                  برابر باشند طبق تعادل یونی) × 0.1
#
# یعنی هر ۱۰ میلی‌اکی‌والان بر لیتر نمک محلول، تقریباً معادل ۱
# دسی‌زیمنس بر متر هدایت الکتریکی ایجاد می‌کند. این یک تقریب شناخته‌شده
# و قابل استناد است (نه عددی اختراعی)، هرچند دقیقاً معادل معادله دقیق
# Kohlrausch (که نیازمند رسانایی مولی استاندارد هر یون λ⁰ و ضریب فعالیت
# یونی است) نیست؛ برای غلظت‌های معمول محلول غذایی (EC 0.5-4 dS/m) خطای
# این تقریب معمولاً کمتر از ۱۰٪ است که برای کاربرد کشاورزی کافی است.
