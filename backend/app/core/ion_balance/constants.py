# محدوده عمومی وقتی نام گیاه در جدول بالا نبود یا مشخص نشده بود
GENERIC_EC_RANGE = {'min': 1.5, 'max': 2.5, 'label': 'عمومی'}


def get_plant_ec_range(plant_name: Optional[str]) -> Dict[str, Any]:
    """
    🆕 دریافت محدوده EC مطلوب بر اساس نام گیاه (در صورت وجود در جدول
    دسته‌بندی)؛ در غیر این صورت بازه عمومی برگردانده می‌شود.

    Args:
        plant_name: نام فارسی گیاه (از فیلد plant_name گزارش)

    Returns:
        Dict: شامل min, max, label و is_specific (آیا برای این گیاه
            به‌طور اختصاصی داده وجود داشت یا از بازه عمومی استفاده شد)
    """
    if not plant_name:
        return {**GENERIC_EC_RANGE, 'is_specific': False}

    name_clean = plant_name.strip()
    if name_clean in PLANT_EC_CATEGORIES:
        return {**PLANT_EC_CATEGORIES[name_clean], 'is_specific': True}

    # جستجوی جزئی (اگر نام گیاه شامل کلیدواژه باشد)
    for key, value in PLANT_EC_CATEGORIES.items():
        if key in name_clean or name_clean in key:
            return {**value, 'is_specific': True}

    return {**GENERIC_EC_RANGE, 'is_specific': False}



