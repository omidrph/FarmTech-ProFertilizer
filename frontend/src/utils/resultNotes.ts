// frontend/src/utils/resultNotes.ts
// فیلتر پیام‌های نتیجهٔ محاسبه: پیام‌های تکراری، عمومی و خالی در بخش «نکات» نمایش داده نمی‌شوند

/** حذف شکلک/نشانه‌های ابتدای پیام و فاصله‌های اضافه */
export const cleanNote = (raw: unknown): string =>
  String(raw ?? '').replace(/^[^\p{L}\p{N}]+/u, '').replace(/\s+/g, ' ').trim();

// پیام‌هایی که در بخش‌های دیگر صفحه (عناصر، تعادل یونی، کیفیت ترکیب) نمایش داده می‌شوند
const COVERED: RegExp[] = [
  /^عنصر .+:\s*(تنها\s*)?\d+\s*%/,
  /^تعادل یونی برقرار نیست/,
  /^الگوریتم به جواب کامل نرسید/,
  /^\d+ کود در ترکیب نهایی استفاده نشدند/,
  /^خطای باقی‌مانده بالا است/,
  /^\d+ عنصر با مقدار صفر/,
  /^\d+ عنصر در داده‌ها وجود ندارد/,
  /^\d+ خطر رسوب شناسایی شده است/,
  /^فقط (کاتیون|آنیون) وجود دارد/,
  /^هیچ کاتیون یا آنیونی/,
];

// پیشنهادهای کلی و بی‌اثر
const GENERIC: RegExp[] = [
  /^افزایش .+ با استفاده از کود مناسب$/,
  /^کاهش .+ یا استفاده از کود با درصد کمتر$/,
  /^عنصر .+ را .*(افزایش|کاهش) دهید/,
  /^برای برقراری تعادل/,
  /^اختلاف (قابل توجه|جزئی)/,
  /^(کاتیون‌ها|آنیون‌ها) \(/,
  /^دوباره بهینه/,
  /^تعداد تکرارها/,
  /^کودهای بیشتری/,
  /^عناصر هدف را با کودهای موجود/,
  /^قیمت کودها را بررسی کنید$/,
  /^لطفاً /,
];

export const isCoveredElsewhere = (t: string): boolean => COVERED.some((re) => re.test(t));
export const isGenericNote = (t: string): boolean => GENERIC.some((re) => re.test(t));